package dev.locus.core.model

import java.util.Locale

/**
 * A tool call's label as data (docs/design/localization.md): Locus's own words ([Phrase]) or text that
 * isn't Locus's to translate ([Verbatim]). [english] is what [toolLabel] returns, word for word, for the
 * model, exports and logs; the app words a [Phrase] in the user's language from the same phrase and
 * values (core/designsystem `ToolLabels.kt`).
 */
sealed interface ToolLabelText {
    val english: String

    /**
     * [phrase] in the past tense when [done], else as what it would do, with [args] put into its
     * `%1$s`, `%2$s`… A plural phrase picks its form by [count], which is also one of its [args].
     */
    data class Phrase(val phrase: ToolPhrase, val done: Boolean, val args: List<Any> = emptyList(), val count: Int? = null) : ToolLabelText {
        override val english: String get() {
            val template = when {
                phrase.plural && count == 1 -> if (done) phrase.pastOne else phrase.presentOne
                else -> if (done) phrase.past else phrase.present
            }!!
            return if (args.isEmpty()) template else String.format(Locale.ROOT, template, *args.toTypedArray())
        }
    }

    /** A connector's own tool ("Notion · search") or a tool Locus has no words for: shown as it is. */
    data class Verbatim(val text: String) : ToolLabelText {
        override val english: String get() = text
    }
}

